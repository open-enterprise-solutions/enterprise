// Strip leading + trailing whitespace.
std::string Trim(const std::string& s)
{
	const auto first = s.find_first_not_of(" \t\r\n");
	if (first == std::string::npos) return std::string();
	const auto last = s.find_last_not_of(" \t\r\n");
	return s.substr(first, last - first + 1);
}

// Decode a possibly-double-quoted dotenv value. Bare values pass
// through (after Trim). Quoted values respect \n \r \t \" \\ escapes.
std::string DecodeValue(const std::string& raw)
{
	const std::string t = Trim(raw);
	if (t.size() >= 2 && t.front() == '"' && t.back() == '"') {
		std::string out;
		out.reserve(t.size());
		for (std::size_t i = 1; i + 1 < t.size(); ++i) {
			const char c = t[i];
			if (c == '\\' && i + 2 < t.size()) {
				const char n = t[i + 1];
				switch (n) {
				case 'n':  out += '\n'; ++i; continue;
				case 'r':  out += '\r'; ++i; continue;
				case 't':  out += '\t'; ++i; continue;
				case '"':  out += '"';  ++i; continue;
				case '\\': out += '\\'; ++i; continue;
				}
			}
			out += c;
		}
		return out;
	}
	return t;
}

// Parse one .env file into a KeyMap. Comments (#-prefixed) and blank
// lines are skipped. Lines missing '=' silently ignored.
KeyMap ParseEnvFile(const wxString& path)
{
	KeyMap m;
	std::ifstream f(std::string(path.utf8_str()), std::ios::binary);
	if (!f.is_open()) return m;
	std::string line;
	while (std::getline(f, line)) {
		// Strip trailing \r — handles CRLF on cross-platform files.
		if (!line.empty() && line.back() == '\r') line.pop_back();
		const std::string trimmed = Trim(line);
		if (trimmed.empty() || trimmed[0] == '#') continue;
		const auto eq = trimmed.find('=');
		if (eq == std::string::npos) continue;
		const std::string key = Trim(trimmed.substr(0, eq));
		const std::string val = DecodeValue(trimmed.substr(eq + 1));
		if (key.empty()) continue;
		m[key] = val;
	}
	return m;
}

// Directory containing per-plugin .env files. Mirrors the plugins.json5
// location so admins can manage all secrets in one place.
wxString GetEnvDir()
{
	wxFileName cfg(pluginsConfig::GetConfigPath());
	return cfg.GetPath();
}

#ifndef _WIN32
// Warn when permissions on `path` are looser than mode 0600.
void WarnIfPermsLoose(const wxString& path)
{
	struct stat st{};
	if (::stat(std::string(path.utf8_str()).c_str(), &st) != 0) return;
	const mode_t mode = st.st_mode & 0777;
	if (mode & 0077) {
		wxLogWarning(wxT("byokEnv: %s has mode 0%o (recommended 0600 — others may read your API key)"),
		             path, static_cast<unsigned>(mode));
	}
}

void TightenPerms(const wxString& path)
{
	::chmod(std::string(path.utf8_str()).c_str(), S_IRUSR | S_IWUSR);
}
#else
void WarnIfPermsLoose(const wxString&) {}
void TightenPerms(const wxString&) {
	// Windows ACL tightening would go through SetSecurityInfo +
	// builtin\Administrators / current-user. Phase 4.2 ships the file
	// in default ACL (NTFS inherits from parent — typically already
	// user-only inside %APPDATA%). A future commit can add SetSecurityInfo
	// for environments where %APPDATA% is itself shared.
}
#endif

