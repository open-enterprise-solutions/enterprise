wxString GetEnvFilePath(const std::string& pluginId)
{
	wxFileName fn(GetEnvDir(), wxString::FromUTF8(pluginId) + wxT(".env"));
	return fn.GetFullPath();
}

PluginEnv LoadAll()
{
	PluginEnv all;
	const wxString dir = GetEnvDir();
	if (!wxDirExists(dir)) return all;

	wxArrayString files;
	wxDir::GetAllFiles(dir, &files, wxT("*.env"), wxDIR_FILES);
	for (const wxString& path : files) {
		WarnIfPermsLoose(path);
		wxFileName fn(path);
		const std::string pluginId = std::string(fn.GetName().utf8_str());
		if (pluginId.empty()) continue;
		all[pluginId] = ParseEnvFile(path);
	}
	return all;
}

int Save(const std::string& pluginId, const KeyMap& keys)
{
	if (pluginId.empty()) return -1;
	const wxString path = GetEnvFilePath(pluginId);

	wxFileName fn(path);
	if (!fn.Mkdir(0700, wxPATH_MKDIR_FULL)) {
		// Mkdir returns false when dir already exists — not an error.
		// Real failures show via the subsequent open() error.
	}

	std::ofstream f(std::string(path.utf8_str()), std::ios::binary | std::ios::trunc);
	if (!f.is_open()) {
		wxLogWarning(wxT("byokEnv: failed to write %s"), path);
		return -1;
	}
	f << "# Generated by OES — do not commit. Permissions: 0600.\n";
	for (const auto& [k, v] : keys) {
		// Always quote values to round-trip control chars / spaces.
		f << k << "=\"";
		for (char c : v) {
			switch (c) {
			case '\\': f << "\\\\"; break;
			case '"':  f << "\\\""; break;
			case '\n': f << "\\n";  break;
			case '\r': f << "\\r";  break;
			case '\t': f << "\\t";  break;
			default:   f << c;
			}
		}
		f << "\"\n";
	}
	f.close();

	TightenPerms(path);
	return 0;
}

std::string Get(const PluginEnv& env, const std::string& pluginId,
                 const std::string& key)
{
	auto pit = env.find(pluginId);
	if (pit == env.end()) return std::string();
	auto kit = pit->second.find(key);
	if (kit == pit->second.end()) return std::string();
	return kit->second;
}

