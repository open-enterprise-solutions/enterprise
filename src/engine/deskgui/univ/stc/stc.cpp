bool ibStyledTextCtrl::Create(wxWindow *parent,
                              wxWindowID id,
                              const wxPoint& pos,
                              const wxSize& size,
                              long style,
                              const wxString& name)
{
    style |= wxVSCROLL | wxHSCROLL | wxWANTS_CHARS | wxCLIP_CHILDREN;

    // SEAM vs wx: created as the engine's control - its scroll bars are the engine's (ibWindow makes them for
    // wxVSCROLL, wxHSCROLL); wxMSW's "Scintilla" window class, which screen readers could be told of, went with
    // wxControl
    if ( !ibControl::Create(parent, id, pos, size, style, wxDefaultValidator, name) )
        return false;

    m_swx = new ScintillaWX(this);
    m_stopWatch.Start();
    m_lastKeyDownConsumed = false;
    m_vScrollBar = nullptr;
    m_hScrollBar = nullptr;
    // Put Scintilla into unicode (UTF-8) mode
    SetCodePage(ibSTC_CP_UTF8);

#ifdef wxHAS_TEXT_INPUT_CLIENT
    // The generic ibSTC backend can display composition itself on these
    // platforms, so prefer inline input instead of relying on an IM module to
    // provide a separate pre-edit window.
    SetIMEInteraction(ibSTC_IME_INLINE);
#endif

    SetInitialSize(size);

    // Reduces flicker on GTK+/X11
    SetBackgroundStyle(wxBG_STYLE_PAINT);

    // Make sure it can take the focus
    SetCanFocus(true);

    // STC doesn't support RTL languages at all
    SetLayoutDirection(wxLayout_LeftToRight);

    // Rely on native double buffering by default, except under Mac where it
    // doesn't work for some reason, see #18085.
#if wxALWAYS_NATIVE_DOUBLE_BUFFER && !defined(__WXMAC__)
    SetBufferedDraw(false);
#else
    SetBufferedDraw(true);
#endif

    // SEAM vs wx: the theme's colours, as an input surface takes them (the content colour, the control text, the
    // highlight) - not the system's
    const wxColour colFg = wxTHEME_COLOUR(CONTROL_TEXT);
    StyleSetForeground(ibSTC_STYLE_DEFAULT, colFg);
    StyleSetBackground(ibSTC_STYLE_DEFAULT, wxTHEME_COLOUR(WINDOW));
    SetCaretForeground(colFg);

    // We also need to set this one because its foreground is hardcoded as
    // black in Scintilla sources.
    StyleSetForeground(ibSTC_STYLE_LINENUMBER, colFg);

    // And foreground for this one is hardcoded as white.
    StyleSetForeground(ibSTC_STYLE_CALLTIP, colFg);

    SetSelForeground(true, wxTHEME_COLOUR(HIGHLIGHT_TEXT));
    SetSelBackground(true, wxTHEME_COLOUR(HIGHLIGHT));

    return true;
}


ibStyledTextCtrl::~ibStyledTextCtrl() {
    delete m_swx;
}


