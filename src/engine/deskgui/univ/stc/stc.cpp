// Find some text in the document.
int ibStyledTextCtrl::FindText(int minPos, int maxPos, const wxString& text,
                               int flags, int* findEnd) {
            Sci_TextToFind  ft;
            ft.chrg.cpMin = minPos;
            ft.chrg.cpMax = maxPos;
            const wxScopedCharBuffer buf = text.utf8_str();
            ft.lpstrText = buf;

            int pos = SendMsg(SCI_FINDTEXT, flags, (sptr_t)&ft);
            if (findEnd) *findEnd=(pos==-1?ibSTC_INVALID_POSITION:ft.chrgText.cpMax);
            return pos;
}

// Draw the document into a display context such as a printer.
 int ibStyledTextCtrl::FormatRange(bool   doDraw,
                int    startPos,
                int    endPos,
                wxDC*  draw,
                wxDC*  target,
                wxRect renderRect,
                wxRect pageRect) {
             Sci_RangeToFormat fr;

             if (endPos < startPos) {
                 wxSwap(startPos, endPos);
             }
             fr.hdc = draw;
             fr.hdcTarget = target;
             fr.rc.top = renderRect.GetTop();
             fr.rc.left = renderRect.GetLeft();
             fr.rc.right = renderRect.GetRight();
             fr.rc.bottom = renderRect.GetBottom();
             fr.rcPage.top = pageRect.GetTop();
             fr.rcPage.left = pageRect.GetLeft();
             fr.rcPage.right = pageRect.GetRight();
             fr.rcPage.bottom = pageRect.GetBottom();
             fr.chrg.cpMin = startPos;
             fr.chrg.cpMax = endPos;

             return SendMsg(SCI_FORMATRANGE, doDraw, (sptr_t)&fr);
}

