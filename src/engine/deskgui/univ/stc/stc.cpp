// the mouse and the keys only - the editor's own events (wxCommandEvent, of the user input category too) still go
// out of a disabled one whose text the program changes
bool ibStyledTextCtrl::TryBefore(wxEvent& event)
{
    if ( !IsEnabled() &&
         (event.IsKindOf(wxCLASSINFO(wxMouseEvent)) || event.IsKindOf(wxCLASSINFO(wxKeyEvent))) )
        return true;

    return ibControl::TryBefore(event);
}


