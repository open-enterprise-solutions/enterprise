// SEAM vs wx: the paint DC is the window's - the client area starts at its origin (inside the engine's border), and
// the buffer, the client area's size as ibWindow::OnPaint takes it, is blitted there; the update region is moved
// into the client area
void ibStyledTextCtrl::OnPaint(wxPaintEvent& WXUNUSED(evt)) {
    const wxPoint origin = GetClientAreaOrigin();
    wxPaintDC dcPaint(this);
    dcPaint.SetDeviceOrigin(origin.x, origin.y);
    wxBufferedDC dc(&dcPaint, GetClientSize());

    // We don't use bounding box for anything, so disable updating it to speed
    // things up a bit.
    dc.DisableAutomaticBoundingBoxUpdates();

    wxRect rectUpdate = GetUpdateRegion().GetBox();
    rectUpdate.Offset(-origin);
    m_swx->DoPaint(&dc, rectUpdate);
}

