// Turn notifications from Scintilla into events


void ibStyledTextCtrl::NotifyChange() {
    ibStyledTextEvent evt(ibEVT_STC_CHANGE, GetId());
    evt.SetEventObject(this);
    GetEventHandler()->ProcessEvent(evt);
}


static void SetEventText(ibStyledTextEvent& evt, const char* text,
                         size_t length) {
    if(!text) return;

    evt.SetString(wxString::FromUTF8(text, length));
}


void ibStyledTextCtrl::NotifyParent(SCNotification* _scn) {
    SCNotification& scn = *_scn;
    ibStyledTextEvent evt(0, GetId());

    evt.SetEventObject(this);
    evt.SetPosition(scn.position);
    evt.SetKey(scn.ch);
    evt.SetModifiers(scn.modifiers);

    switch (scn.nmhdr.code) {
    case SCN_STYLENEEDED:
        evt.SetEventType(ibEVT_STC_STYLENEEDED);
        break;

    case SCN_CHARADDED:
        evt.SetEventType(ibEVT_STC_CHARADDED);
        break;

    case SCN_SAVEPOINTREACHED:
        evt.SetEventType(ibEVT_STC_SAVEPOINTREACHED);
        break;

    case SCN_SAVEPOINTLEFT:
        evt.SetEventType(ibEVT_STC_SAVEPOINTLEFT);
        break;

    case SCN_MODIFYATTEMPTRO:
        evt.SetEventType(ibEVT_STC_ROMODIFYATTEMPT);
        break;

    case SCN_DOUBLECLICK:
        evt.SetEventType(ibEVT_STC_DOUBLECLICK);
        evt.SetLine(scn.line);
        break;

    case SCN_UPDATEUI:
        evt.SetEventType(ibEVT_STC_UPDATEUI);
        evt.SetUpdated(scn.updated);
        break;

    case SCN_MODIFIED:
        evt.SetEventType(ibEVT_STC_MODIFIED);
        evt.SetModificationType(scn.modificationType);
        SetEventText(evt, scn.text, scn.length);
        evt.SetLength(scn.length);
        evt.SetLinesAdded(scn.linesAdded);
        evt.SetLine(scn.line);
        evt.SetFoldLevelNow(scn.foldLevelNow);
        evt.SetFoldLevelPrev(scn.foldLevelPrev);
        evt.SetToken(scn.token);
        evt.SetAnnotationLinesAdded(scn.annotationLinesAdded);
        break;

    case SCN_MACRORECORD:
        evt.SetEventType(ibEVT_STC_MACRORECORD);
        evt.SetMessage(scn.message);
        evt.SetWParam(scn.wParam);
        evt.SetLParam(scn.lParam);
        break;

    case SCN_MARGINCLICK:
        evt.SetEventType(ibEVT_STC_MARGINCLICK);
        evt.SetMargin(scn.margin);
        break;

    case SCN_NEEDSHOWN:
        evt.SetEventType(ibEVT_STC_NEEDSHOWN);
        evt.SetLength(scn.length);
        break;

    case SCN_PAINTED:
        evt.SetEventType(ibEVT_STC_PAINTED);
        break;

    case SCN_USERLISTSELECTION:
        evt.SetEventType(ibEVT_STC_USERLISTSELECTION);
        evt.SetListType(scn.listType);
        SetEventText(evt, scn.text, strlen(scn.text));
        evt.SetListCompletionMethod(scn.listCompletionMethod);
        break;

    case SCN_DWELLSTART:
        evt.SetEventType(ibEVT_STC_DWELLSTART);
        evt.SetX(scn.x);
        evt.SetY(scn.y);
        break;

    case SCN_DWELLEND:
        evt.SetEventType(ibEVT_STC_DWELLEND);
        evt.SetX(scn.x);
        evt.SetY(scn.y);
        break;

    case SCN_ZOOM:
        evt.SetEventType(ibEVT_STC_ZOOM);
        break;

    case SCN_HOTSPOTCLICK:
        evt.SetEventType(ibEVT_STC_HOTSPOT_CLICK);
        break;

    case SCN_HOTSPOTDOUBLECLICK:
        evt.SetEventType(ibEVT_STC_HOTSPOT_DCLICK);
        break;

    case SCN_HOTSPOTRELEASECLICK:
        evt.SetEventType(ibEVT_STC_HOTSPOT_RELEASE_CLICK);
        break;

    case SCN_INDICATORCLICK:
        evt.SetEventType(ibEVT_STC_INDICATOR_CLICK);
        break;

    case SCN_INDICATORRELEASE:
        evt.SetEventType(ibEVT_STC_INDICATOR_RELEASE);
        break;

    case SCN_CALLTIPCLICK:
        evt.SetEventType(ibEVT_STC_CALLTIP_CLICK);
        break;

    case SCN_AUTOCSELECTION:
        evt.SetEventType(ibEVT_STC_AUTOCOMP_SELECTION);
        evt.SetListType(scn.listType);
        SetEventText(evt, scn.text, strlen(scn.text));
        evt.SetListCompletionMethod(scn.listCompletionMethod);
        break;

    case SCN_AUTOCCANCELLED:
        evt.SetEventType(ibEVT_STC_AUTOCOMP_CANCELLED);
        break;

    case SCN_AUTOCCHARDELETED:
        evt.SetEventType(ibEVT_STC_AUTOCOMP_CHAR_DELETED);
        break;

    case SCN_AUTOCCOMPLETED:
        evt.SetEventType(ibEVT_STC_AUTOCOMP_COMPLETED);
        evt.SetListType(scn.listType);
        SetEventText(evt, scn.text, strlen(scn.text));
        evt.SetListCompletionMethod(scn.listCompletionMethod);
        break;

    case SCN_MARGINRIGHTCLICK:
        evt.SetEventType(ibEVT_STC_MARGIN_RIGHT_CLICK);
        evt.SetMargin(scn.margin);
        break;

    case SCN_AUTOCSELECTIONCHANGE:
        evt.SetEventType(ibEVT_STC_AUTOCOMP_SELECTION_CHANGE);
        evt.SetListType(scn.listType);
        SetEventText(evt, scn.text, strlen(scn.text));
        break;

    default:
        return;
    }

    GetEventHandler()->ProcessEvent(evt);
}

